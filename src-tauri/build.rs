use std::fs;
use std::path::Path;

fn main() {
    embed_textbook_json();
    tauri_build::build();
}

/// Scan `resources/textbooks/*.json` and embed every file with `include_str!`.
/// The packaged app and the tests both read this list, so lookup does not depend
/// on the process working directory.
fn embed_textbook_json() {
    let manifest = std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR");
    let dir = Path::new(&manifest).join("resources/textbooks");
    println!("cargo:rerun-if-changed=resources/textbooks");

    let mut files: Vec<_> = fs::read_dir(&dir)
        .unwrap_or_else(|err| panic!("read {}: {err}", dir.display()))
        .map(|entry| entry.expect("textbook directory entry").path())
        .filter(|path| path.extension().and_then(|ext| ext.to_str()) == Some("json"))
        .collect();
    files.sort();
    if files.is_empty() {
        panic!("resources/textbooks has no json files");
    }

    let mut out = String::from("// Generated by build.rs. Do not edit.\n");
    out.push_str("pub static BUILTIN_TEXTBOOK_JSON: &[&str] = &[\n");
    for path in &files {
        println!("cargo:rerun-if-changed={}", path.display());
        let rendered = path.to_string_lossy().replace('\\', "/");
        out.push_str(&format!("    include_str!(r#\"{rendered}\"#),\n"));
    }
    out.push_str("];\n");

    let dest = Path::new(&std::env::var("OUT_DIR").expect("OUT_DIR")).join("builtin_textbooks.rs");
    fs::write(&dest, out).unwrap_or_else(|err| panic!("write {}: {err}", dest.display()));
}
